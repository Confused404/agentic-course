"""python -m agentlab.context gen [--out PATH] [--lengths 10,30,50] [--seed 0]   (GIVEN)
                           report RUN_DIR                                    (Node 06 SPEC §8)
                           breakdown RUN_DIR --task ID [--trial 0]           (Node 06 SPEC §8)"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from agentlab.context.longconv import LENGTHS, generate_suite


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m agentlab.context")
    sub = p.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen", help="generate the long-conversation suite")
    g.add_argument("--out", default="nodes/06-context-memory/evals/long/long.yaml")
    g.add_argument("--lengths", default=",".join(map(str, LENGTHS)))
    g.add_argument("--seed", type=int, default=0)
    r = sub.add_parser("report", help="success vs tokens per variant, from an eval or experiment run directory")
    r.add_argument("run_dir")
    b = sub.add_parser("breakdown", help="estimated tokens by component at the end of one trial")
    b.add_argument("run_dir")
    b.add_argument("--task", required=True)
    b.add_argument("--trial", type=int, default=0)
    b.add_argument("--variant", default=None, help="model label / experiment side (baseline|candidate)")
    a = p.parse_args(argv)
    if a.cmd == "report":
        from agentlab.context.report import render_context_report, write_tokens_by_turn
        from agentlab.evals.runner import load_trials
        run = Path(a.run_dir)
        trials = load_trials(run / "trials.jsonl")
        md = render_context_report(trials, title=run.name)
        (run / "context_report.md").write_text(md)
        write_tokens_by_turn(trials, run / "tokens_by_turn.csv")
        print(md)
        print(f"wrote {run / 'context_report.md'} and {run / 'tokens_by_turn.csv'}")
        return 0
    if a.cmd == "breakdown":
        from agentlab.context.tokens import breakdown
        from agentlab.evals.runner import load_trials
        from agentlab.llm.types import Message
        ts = [t for t in load_trials(Path(a.run_dir) / "trials.jsonl") if t.task_id == a.task and t.trial == a.trial
              and (a.variant is None or t.model == a.variant)]
        if not ts:
            raise SystemExit("no such trial (check --task, --trial, --variant)")
        if len(ts) > 1:
            raise SystemExit(f"{len(ts)} trials match; pick one with --variant {sorted({t.model for t in ts})}")
        msgs = [Message.from_dict(d) for d in ts[0].transcript]
        b = breakdown("", [], msgs)
        fixed = ts[0].extra.get("fixed_tokens", {})
        b["system"], b["tools"] = fixed.get("system", 0), fixed.get("tools", 0)
        b["total"] = sum(v for k, v in b.items() if k != "total")
        for k, v in b.items():
            print(f"{k:16} {v:>9,}  {v / b['total']:6.1%}" if b["total"] else f"{k:16} {v:>9,}")
        for st in ts[0].extra.get("turn_stats", []):
            if st.get("summary"):
                print(f"\n--- summary the model saw from turn {st['turn']} (session {st.get('session', 0)}) ---\n"
                      f"{st['summary']}")
        print("\n(the token counts are for the transcript: everything that happened. The model saw less if a strategy trimmed it; see "
              "turn_stats in trials.jsonl for what was actually sent.)")
        return 0
    if a.cmd == "gen":
        tasks = generate_suite(tuple(int(x) for x in a.lengths.split(",")), seed=a.seed)
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        header = "# GENERATED by `python -m agentlab.context gen` (agentlab/context/longconv.py). Don't edit by hand.\n"
        Path(a.out).write_text(header + yaml.safe_dump(tasks, sort_keys=False, allow_unicode=True, width=120))
        print(f"wrote {len(tasks)} tasks to {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
